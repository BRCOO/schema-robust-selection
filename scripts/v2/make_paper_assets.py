def schema_aware_tradeoff(gaps: tuple = GAPS, name: str = "schema_aware_tradeoff") -> None:
    """Known single target: mean (SRS - reference) of the target AUPRC and of the source (internal test)
    AUPRC over the generator x target cells where both registries exist."""
    inputs, cells_by_gap = [], {}
    for gap in gaps:
        path = ROOT / f"artifacts/v2/schema_aware/f_mimic_iv_{_label(gap)}/single_target.csv"
        if not path.exists():
            continue
        inputs.append(path)
        cells_by_gap[gap] = {(r["method"], r["target"], r["registry"]): r for r in read_csv(path) if not r.get("error")}
    if not cells_by_gap:
        return
    table = []
    for ref in TRADEOFF_REFERENCES:
        line, seen = [SCHEMA_REGISTRY_LABEL.get(ref, ref)], False
        for gap, cell in cells_by_gap.items():
            keys = [(m, tg) for (m, tg, reg) in cell if reg == ref and (m, tg, "srs_aware") in cell]
            if not keys:
                line.append("--")
                continue
            seen = True
            d_target = np.mean([float(cell[(m, tg, "srs_aware")]["target_auprc"]) - float(cell[(m, tg, ref)]["target_auprc"]) for m, tg in keys])
            d_source = np.mean([float(cell[(m, tg, "srs_aware")]["internal_auprc"]) - float(cell[(m, tg, ref)]["internal_auprc"]) for m, tg in keys])
            line.append(f"{d_target:+.3f} / {d_source:+.3f} ({len(keys)})")
        if seen:
            table.append(line)
    write_table(
        name,
        ["SRS (target known) minus", *[f"{'gap ' if isinstance(g, int) else ''}{_label_text(g)}: target / source (cells)" for g in cells_by_gap]],
        table,
        "Known single target: mean AUPRC difference SRS minus the reference on the target and on the source (internal test split), over the generator x target cells where both registries exist. Hard filters match SRS on the target but lose on the source; schema-unaware selectors match it on the source but lose on the target.",
        *inputs,
    )


