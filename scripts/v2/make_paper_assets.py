def comparison_rows(gap: int | str, variant: str = "default") -> tuple[list[dict[str, str]], Path] | tuple[None, None]:
    """Rows of the main comparison (``default``: a-priori selector weights) or of the
    validation-tuned selector analysis (``tuned``: same native rows, selector rows with the
    weights chosen on validation; 2000 bootstrap replicates in both)."""
    if variant == "tuned":
        path = ROOT / f"artifacts/v2/selector_analysis/f_mimic_iv_{_label(gap)}/tuned.csv"
    else:
        path = ROOT / f"artifacts/v2/comparison/f_mimic_iv_{_label(gap)}/comparison_rows.csv"
    return (read_csv(path), path) if path.exists() else (None, None)


def _suffix(variant: str) -> str:
    return "" if variant == "default" else f"_{variant}"


def _selection_label(selection: str, variant: str) -> str:
    if selection == "v2_selector" and variant == "tuned":
        return "+ selector (val.-tuned)"
    return SELECTION_LABEL[selection]


def main_tables(gap: int | str = 1, variant: str = "default") -> None:
    rows, path = comparison_rows(gap, variant)
    if rows is None:
        return
    sx = _suffix(variant)
    order = {m: i for i, m in enumerate(METHODS)}
    rows = sorted([r for r in rows if not r.get("error")], key=lambda r: (order.get(r["method"], 99), r["selection"]))
    prev = fmt(rows[0].get("prevalence"))
    weights = "" if variant == "default" else " Selector weights chosen per generator on validation."
    write_table(
        f"discovery_internal_{_label(gap)}{sx}",
        ["Method", "Selection", "AUPRC [95% CI]", "AUROC", "Redundancy", "Anchor cov.", "Feature cov.", "Never fire (train)"],
        [[METHOD_LABEL[r["method"]], _selection_label(r["selection"], variant), ci(r, "auprc"), fmt(r.get("auroc")), fmt(r.get("redundancy")), r.get("anchor_group_coverage"), r.get("feature_coverage"), r.get("n_never_fire_train")] for r in rows],
        f"Internal MIMIC-IV test (prevalence {prev}); K = 10; patient-clustered bootstrap CIs.{weights}",
        path,
    )
    write_table(
        f"discovery_external_{_label(gap)}{sx}",
        ["Method", "Selection", "eICU AUPRC [95% CI]", "eICU survival", "HiRID AUPRC [95% CI]", "HiRID survival"],
        [[METHOD_LABEL[r["method"]], _selection_label(r["selection"], variant), ci(r, "eicu_auprc"), fmt(r.get("eicu_schema_survival"), 2), ci(r, "hirid_auprc"), fmt(r.get("hirid_schema_survival"), 2)] for r in rows],
        f"External refiring without repair (eICU prevalence {fmt(rows[0].get('eicu_prevalence'))}, HiRID {fmt(rows[0].get('hirid_prevalence'))}).{weights}",
        path,
    )
    write_table(
        f"schema_shift_{_label(gap)}{sx}",
        ["Method", "Selection", *[SHIFT_LABEL[t] + " AUPRC/surv." for t in SHIFT_TARGETS]],
        [[METHOD_LABEL[r["method"]], _selection_label(r["selection"], variant), *[f"{fmt(r.get(t + '_auprc'))} / {fmt(r.get(t + '_schema_survival'), 2)}" for t in SHIFT_TARGETS]] for r in rows],
        f"Controlled schema shift on the internal test split (population fixed; prevalence {prev}).{weights}",
        path,
    )
    if variant != "default":
        return
    full = json.loads((path.parent / "comparison_full.json").read_text(encoding="utf-8"))
    paired = full.get("paired_vs_reference", [])
    if paired:
        def name(key: str) -> str:
            method, selection = key.split("|")
            return f"{METHOD_LABEL.get(method, method)} ({SELECTION_LABEL.get(selection, selection)})"
        write_table(
            f"paired_vs_fmg_{_label(gap)}",
            ["Comparison (minus FMG-Bridge native)", "AUPRC difference", "95% CI", "P(diff <= 0)"],
            [[name(d["comparison"].split(" - ")[0]), fmt(d["point_diff"]), f"[{fmt(d['low'])}, {fmt(d['high'])}]", fmt(d["frac_le_zero"])] for d in paired],
            "Paired patient-clustered bootstrap of internal test AUPRC.",
            path.parent / "comparison_full.json",
        )
    timings = full.get("timings_seconds", {}).get("pool_build", {})
    if timings:
        write_table(
            f"pool_build_time_{_label(gap)}",
            ["Method", "Pool build (s)", "Candidates"],
            [[METHOD_LABEL.get(m, m), fmt(t, 0), full["timings_seconds"]["n_candidates"].get(m)] for m, t in timings.items()],
            "Wall time to mine, rank and fire each method's candidate pool (single process; FMG excludes per-episode mining).",
            path.parent / "comparison_full.json",
        )


def figure_internal_external(gap: int = 1, variant: str = "default") -> None:
    rows, path = comparison_rows(gap, variant)
    if rows is None:
        return
    rows = [r for r in rows if not r.get("error")]
    panels = (("", "Internal test (MIMIC-IV)"), ("eicu_", "eICU (external)"), ("hirid_", "HiRID (external)"))
    fig, axes = plt.subplots(1, 3, figsize=(10.5, 3.0), sharey=True)
    y = {m: i for i, m in enumerate(reversed(METHODS))}
    handles: dict[str, Any] = {}
    for ax, (prefix, title) in zip(axes, panels):
        style_axes(ax)
        prevalence = next((float(r[prefix + "prevalence"]) for r in rows if r.get(prefix + "prevalence")), None)
        if prevalence is not None:
            handles["prevalence (uninformative score)"] = ax.axvline(prevalence, color=GRAY, linestyle=(0, (3, 3)), linewidth=1.0)
        for selection, offset, color, face in (("native", 0.14, BLUE, "white"), ("v2_selector", -0.14, ORANGE, ORANGE)):
            for r in rows:
                if r["selection"] != selection or not r.get(prefix + "auprc"):
                    continue
                point, low, high = (float(r[prefix + k]) for k in ("auprc", "auprc_low", "auprc_high"))
                yy = y[r["method"]] + offset
                ax.plot([low, high], [yy, yy], color=color, linewidth=2.0, solid_capstyle="round")
                (marker,) = ax.plot([point], [yy], marker="o", markersize=7, markerfacecolor=face, markeredgecolor=color, markeredgewidth=2.0, linestyle="none")
                handles.setdefault(_selection_label(selection, variant), marker)
        ax.set_title(title, fontsize=9, color=INK, loc="left")
        ax.set_xlabel("AUPRC (95% CI)", fontsize=8, color=INK_2)
    axes[0].set_yticks(list(y.values()), [METHOD_LABEL[m] for m in y])
    order = [k for k in (SELECTION_LABEL["native"], _selection_label("v2_selector", variant), "prevalence (uninformative score)") if k in handles]
    fig.legend([handles[k] for k in order], order, loc="upper center", ncol=len(order), frameon=False, fontsize=8, bbox_to_anchor=(0.5, 1.08))
    fig.tight_layout()
    save(fig, f"discovery_internal_external_{_label(gap)}{_suffix(variant)}", path)


def figure_schema_shift(gap: int = 1, variant: str = "default") -> None:
    rows, path = comparison_rows(gap, variant)
    if rows is None:
        return
    rows = [r for r in rows if not r.get("error")]
    order = {m: i for i, m in enumerate(METHODS)}
    rows.sort(key=lambda r: (order.get(r["method"], 99), r["selection"]))
    columns = ("internal", *SHIFT_TARGETS, "eicu", "hirid")
    survival = np.full((len(rows), len(columns)), np.nan)
    auprc = np.full_like(survival, np.nan)
    for i, r in enumerate(rows):
        for j, c in enumerate(columns):
            if c == "internal":
                survival[i, j], auprc[i, j] = 1.0, float(r["auprc"])
            else:
                if r.get(c + "_schema_survival"):
                    survival[i, j] = float(r[c + "_schema_survival"])
                if r.get(c + "_auprc"):
                    auprc[i, j] = float(r[c + "_auprc"])
    from matplotlib.colors import LinearSegmentedColormap

    cmap = LinearSegmentedColormap.from_list("blue_seq", ["#e8f0fb", "#9ec5f4", "#3987e5", "#1c5cab", "#0d366b"])
    fig, ax = plt.subplots(figsize=(9.0, 4.2))
    image = ax.imshow(survival, cmap=cmap, vmin=0.0, vmax=1.0, aspect="auto")
    for i in range(len(rows)):
        for j in range(len(columns)):
            if np.isfinite(auprc[i, j]):
                ax.text(j, i, f"{auprc[i, j]:.2f}", ha="center", va="center", fontsize=7, color="#ffffff" if survival[i, j] > 0.55 else INK)
    ax.set_xticks(range(len(columns)), [SHIFT_LABEL[c] for c in columns], fontsize=8, rotation=20, ha="right")
    ax.set_yticks(range(len(rows)), [f"{METHOD_LABEL[r['method']]} ({_selection_label(r['selection'], variant)})" for r in rows], fontsize=8)
    for spine in ax.spines.values():
        spine.set_visible(False)
    ax.set_xticks(np.arange(-0.5, len(columns)), minor=True)
    ax.set_yticks(np.arange(-0.5, len(rows)), minor=True)
    ax.grid(which="minor", color="#fcfcfb", linewidth=2)
    ax.tick_params(which="minor", length=0)
    bar = fig.colorbar(image, ax=ax, fraction=0.03, pad=0.02)
    bar.set_label("schema survival (share of K programs)", fontsize=8, color=INK_2)
    bar.ax.tick_params(labelsize=7)
    ax.set_title("Cell text: AUPRC under the target schema (frozen probe, no repair)", fontsize=8, color=INK_2, loc="left")
    fig.tight_layout()
    save(fig, f"schema_shift_{_label(gap)}{_suffix(variant)}", path)


