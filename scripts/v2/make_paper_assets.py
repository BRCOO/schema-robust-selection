def _tally_rows(pairs: Sequence[tuple[str, str]], dirs: Sequence[tuple[str, Path]]) -> list[list[str]]:
    """better / n.s. / worse and mean difference over runs, internal and mean target (surrogates)."""
    rows = []
    for a, b in pairs:
        cells = {"internal": [], "target": []}
        for _, base in dirs:
            for r in read_csv(base / "paired_internal.csv"):
                if r["a"] == a and r["b"] == b:
                    cells["internal"].append(r)
            for r in read_csv(base / "paired_targets.csv"):
                if r["target"] == "mean_over_targets" and r["a"] == f"{a}:composite" and r["b"] == f"{b}:composite":
                    cells["target"].append(r)
        if not cells["internal"]:
            continue
        out = [EXTRA_LABEL.get(b, b), str(len(cells["internal"]))]
        for metric in ("internal", "target"):
            counts = [0, 0, 0]
            for r in cells[metric]:
                counts[0 if float(r["low"]) > 0 else (2 if float(r["high"]) < 0 else 1)] += 1
            out += ["/".join(map(str, counts)), f"{np.mean([float(r['point_diff']) for r in cells[metric]]):+.3f}"]
        rows.append(out)
    return rows


