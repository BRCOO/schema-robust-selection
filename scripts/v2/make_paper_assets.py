def supervised_tables(gap: int | str = 1, variant: str = "") -> None:
    """Seed-0 AUPRC with its patient-clustered CI, and the mean +- SD over seeds (the neural
    models vary by seed, so a seed-mean point with a seed-0 interval would not be coherent)."""
    from src.icu.v2.stats import metric_value

    base = ROOT / f"artifacts/v2/supervised/f_mimic_iv_{_label(gap)}{variant}"
    internal = base / "supervised_v2_test_predictions.csv"
    if not internal.exists():
        return
    def summarize(path: Path, cohort_key: str | None) -> dict[tuple[str, str], dict[str, Any]]:
        groups: dict[tuple[str, str], dict[str, list]] = defaultdict(lambda: defaultdict(list))
        for r in read_csv(path):
            cohort = r.get(cohort_key, "internal") if cohort_key else "internal"
            groups[(r["model"], cohort)][r["seed"]].append((int(r["label"]), float(r["prob"]), r["subject_id"]))
        out = {}
        for key, seeds in groups.items():
            points = []
            seed0 = None
            for seed, items in sorted(seeds.items(), key=lambda kv: int(kv[0])):
                y = np.array([i[0] for i in items]); p = np.array([i[1] for i in items]); g = np.array([i[2] for i in items])
                points.append(metric_value(y, p, "auprc"))
                if seed0 is None:
                    seed0 = patient_cluster_bootstrap(y, p, g, "auprc", n_boot=1000, seed=0)
            out[key] = {"mean": float(np.mean(points)), "sd": float(np.std(points)), "n_seeds": len(points), "seed0": seed0}
        return out
    stats = summarize(internal, None)
    inputs = [internal]
    external = next((p for p in base.glob("*external*predictions*.csv")), None)
    if external is not None:
        stats.update(summarize(external, "cohort"))
        inputs.append(external)
    models = sorted({m for m, _ in stats}, key=lambda m: -stats[(m, "internal")]["seed0"]["point"])
    cohorts = [c for c in ("internal", "eicu", "hirid") if any((m, c) in stats for m in models)]
    rows = []
    for m in models:
        row = [m]
        for c in cohorts:
            s = stats.get((m, c))
            if s is None:
                row += ["--", "--"]
                continue
            b = s["seed0"]
            row += [f"{b['point']:.3f} [{b['low']:.3f}, {b['high']:.3f}]", f"{s['mean']:.3f} +- {s['sd']:.3f}"]
        rows.append(row)
    header = ["Model"]
    for c in cohorts:
        name = "Internal" if c == "internal" else SHIFT_LABEL.get(c, c)
