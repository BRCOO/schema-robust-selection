AKI_TAG = "aki_gap6h"  # second task: AKI onset (KDIGO creatinine), prediction gap 6 h


def _label(gap: int | str) -> str:
    """Run label in paths and file names: an int gap g -> 'gap{g}h'; a str label as is."""
    return gap if isinstance(gap, str) else f"gap{gap}h"


def _label_text(gap: int | str) -> str:
    """Run label in table cells: 'g h', or 'AKI, g h' for the AKI task."""
    if isinstance(gap, int):
        return f"{gap} h"
    found = re.fullmatch(r"(?:(\w+?)_)?gap(\d+)h", gap)
    if not found:
        return gap
    return (f"{found.group(1).upper()}, " if found.group(1) else "") + f"{found.group(2)} h"


