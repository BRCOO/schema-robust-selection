def read_csv(path: Path) -> list[dict[str, str]]:
    with open(path, encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def write_table(name: str, header: Sequence[str], rows: Sequence[Sequence[Any]], caption: str, *inputs: Path) -> None:
    TABLES.mkdir(parents=True, exist_ok=True)
    with open(TABLES / f"{name}.csv", "w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(header)
        writer.writerows(rows)
    cols = "l" + "r" * (len(header) - 1)
    def esc(value: Any) -> str:
        return str(value).replace("_", "\\_").replace("%", "\\%").replace("&", "\\&")
    lines = [
        "% generated by scripts/v2/make_paper_assets.py -- do not edit by hand",
        f"% {caption}",
        f"\\begin{{tabular}}{{{cols}}}",
        "\\toprule",
        " & ".join(esc(h) for h in header) + " \\\\",
        "\\midrule",
        *[" & ".join(esc(c) for c in row) + " \\\\" for row in rows],
        "\\bottomrule",
        "\\end{tabular}",
    ]
    (TABLES / f"{name}.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    note(f"tables/{name}.csv|.tex", *inputs)


def fmt(value: Any, digits: int = 3) -> str:
    try:
        x = float(value)
    except (TypeError, ValueError):
        return "--"
    return "--" if not np.isfinite(x) else f"{x:.{digits}f}"


def ci(row: dict[str, str], prefix: str) -> str:
    return f"{fmt(row.get(prefix))} [{fmt(row.get(prefix + '_low'))}, {fmt(row.get(prefix + '_high'))}]"


def style_axes(ax: plt.Axes) -> None:
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color("#b9b8b2")
    ax.tick_params(colors=INK_2, labelsize=8)
    ax.grid(axis="x", color="#e7e6e1", linewidth=0.6)
    ax.set_axisbelow(True)


def direct_labels(ax: plt.Axes, items: Sequence[tuple[float, float, str, str]], min_gap: float = 0.07, dx: float = 0.03) -> None:
    """Direct labels at line ends without overlaps.

    ``items`` = (x, y, text, color) of each line's last point in data units. Labels are spread
    vertically in axes coordinates (so log axes work) with at least ``min_gap`` between them;
    a moved label gets a thin leader line in the series color. Text stays in ink.
    """
    ax.autoscale_view()
    to_axes = ax.transAxes.inverted()
    points = []
    for x, y, label, color in items:
        ax_x, ax_y = to_axes.transform(ax.transData.transform((x, y)))
        points.append((ax_x, ax_y, label, color))
    points.sort(key=lambda p: p[1])
    placed: list[float] = []
    for _, ax_y, _, _ in points:
        placed.append(max(ax_y, placed[-1] + min_gap) if placed else ax_y)
    overflow = (placed[-1] - 0.98) if placed else 0.0
    if overflow > 0:
        placed = [p - overflow for p in placed]
        for i in range(len(placed) - 2, -1, -1):
            placed[i] = min(placed[i], placed[i + 1] - min_gap)
    for (ax_x, ax_y, label, color), y in zip(points, placed):
        moved = abs(y - ax_y) > 0.01
        ax.annotate(
            label, xy=(ax_x, ax_y), xycoords="axes fraction", xytext=(ax_x + dx, y), textcoords="axes fraction",
            fontsize=7, color=INK, va="center", ha="left", annotation_clip=False,
            arrowprops=dict(arrowstyle="-", color=color, linewidth=0.7, shrinkA=0, shrinkB=1) if moved else None,
        )


def save(fig: plt.Figure, name: str, *inputs: Path) -> None:
    FIGURES.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIGURES / f"{name}.pdf", bbox_inches="tight")
    fig.savefig(FIGURES / f"{name}.png", dpi=200, bbox_inches="tight")
    plt.close(fig)
    note(f"figures/{name}.pdf|.png", *inputs)


