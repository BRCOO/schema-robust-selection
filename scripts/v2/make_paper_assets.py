def gap_sensitivity() -> None:
    table, inputs = [], []
    series: dict[str, list[tuple[int, float]]] = defaultdict(list)
    for gap in GAPS:
        rows, path = comparison_rows(gap)
        if rows is None:
            continue
        inputs.append(path)
        for r in rows:
            if r.get("error"):
                continue
            table.append([f"{gap} h", METHOD_LABEL[r["method"]], SELECTION_LABEL[r["selection"]], fmt(r.get("prevalence")), fmt(r.get("auprc")), fmt(r.get("auroc")), fmt(r.get("eicu_auroc")), fmt(r.get("hirid_auroc"))])
            if r["selection"] == "v2_selector" or r["method"] == "fmg_bridge" and r["selection"] == "native":
                key = r["method"] if r["selection"] == "v2_selector" else "fmg_bridge_native"
                series[key].append((gap, float(r["auroc"])))
    if not table:
        return
    for gap in GAPS:
        path = ROOT / f"artifacts/v2/selector_analysis/f_mimic_iv_{_label(gap)}/tuned.csv"
        if not path.exists():
            continue
        inputs.append(path)
        for r in read_csv(path):
            if r["selection"] == "v2_selector" and not r.get("error"):
                table.append([f"{gap} h", METHOD_LABEL[r["method"]], "+ selector (val.-tuned)", fmt(r.get("prevalence")), fmt(r.get("auprc")), fmt(r.get("auroc")), fmt(r.get("eicu_auroc")), fmt(r.get("hirid_auroc"))])
    write_table("gap_sensitivity", ["Gap", "Method", "Selection", "Prevalence", "AUPRC", "AUROC", "eICU AUROC", "HiRID AUROC"], table, "Prediction-gap sensitivity.", *inputs)
    # small multiples: one panel per generator, native top-K vs + selector (a-priori weights)
    # vs + selector (weights chosen on validation), internal test AUROC (prevalence-free)
    lines: dict[tuple[str, str], list[tuple[int, float]]] = defaultdict(list)
    for gap in GAPS:
        for variant in ("default", "tuned"):
            rows, _ = comparison_rows(gap, variant)
            for r in rows or []:
                if r.get("error") or not r.get("auroc"):
                    continue
                key = "native" if r["selection"] == "native" else ("selector" if variant == "default" else "tuned")
                if key == "native" and variant == "tuned":
                    continue
                lines[(r["method"], key)].append((gap, float(r["auroc"])))
    if len({g for pts in lines.values() for g, _ in pts}) < 2:
        return
    fig, axes = plt.subplots(1, len(METHODS), figsize=(12.5, 2.7), sharey=True)
    styles = {
        "native": (BLUE, "white", "-", SELECTION_LABEL["native"]),
        "selector": (GRAY, GRAY, (0, (3, 2)), "+ selector (a-priori weights)"),
        "tuned": (ORANGE, ORANGE, "-", "+ selector (val.-tuned)"),
    }
    handles = {}
    for ax, method in zip(axes, METHODS):
        style_axes(ax)
        ax.grid(axis="y", color="#e7e6e1", linewidth=0.6)
        for key, (color, face, dash, label) in styles.items():
            pts = sorted(lines.get((method, key), []))
            if not pts:
                continue
            (line,) = ax.plot([g for g, _ in pts], [v for _, v in pts], color=color, linewidth=2 if key != "selector" else 1.4, linestyle=dash,
                              marker="o", markersize=6, markerfacecolor=face, markeredgecolor=color, markeredgewidth=1.6)
            handles.setdefault(label, line)
        ax.set_title(METHOD_LABEL[method], fontsize=9, color=INK, loc="left")
        ax.set_xticks(list(GAPS), [f"{g} h" for g in GAPS])
        ax.set_xlim(0.6, 4.4)
        ax.set_xlabel("prediction gap", fontsize=8, color=INK_2)
    axes[0].set_ylabel("internal test AUROC", fontsize=8, color=INK_2)
    fig.legend(list(handles.values()), list(handles.keys()), loc="upper center", ncol=len(handles), frameon=False, fontsize=8, bbox_to_anchor=(0.5, 1.1))
    fig.tight_layout()
    save(fig, "gap_sensitivity", *inputs)


